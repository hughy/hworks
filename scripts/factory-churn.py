#!/usr/bin/env python3
"""First-parent churn primitives for factory-metrics.py. No network or working-tree writes."""
import json, os, re, subprocess, sys, fnmatch
from datetime import datetime, timezone

EMPTY = "4b825dc642cb6eb9a060e54bf8d69288fbee4904"
DAY = 86400

EXCL_NAMES = {"go.sum", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "Cargo.lock",
              "bun.lockb", "poetry.lock", "uv.lock", "Gemfile.lock", "composer.lock", "flake.lock"}
EXCL_GLOBS = ["*.lock", "*.pb.go", "*.pb.gw.go", "*_gen.go", "*.gen.go", "*_pb2.py", "*_pb.ts", "*_pb.js"]
EXCL_DIRS = ["vendor/", "node_modules/", "third_party/", "testdata/"]
GEN_RE = re.compile(r"(Code generated .* DO NOT EDIT|@generated|Generated by .*Do not edit|DO NOT EDIT)", re.I)


def git(repo, *args, check=True):
    r = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, errors="replace")
    if check and r.returncode:
        raise RuntimeError(f"git {args}: {r.stderr}")
    return r.stdout


def excluded_path(repo, path, extra_dirs):
    base = path.rsplit("/", 1)[-1]
    if base in EXCL_NAMES or any(fnmatch.fnmatch(base, g) for g in EXCL_GLOBS):
        return "lock/generated name"
    p = "/" + path
    for d in EXCL_DIRS + extra_dirs:
        if p.startswith("/" + d) or ("/" + d) in p:
            return "vendored/fixture dir " + d
    return None


_gen_cache = {}


def generated_header(repo, rev, path):
    k = (os.path.realpath(repo), rev, path)
    if k not in _gen_cache:
        head = git(repo, "show", f"{rev}:{path}", check=False)[:2000]
        _gen_cache[k] = bool(GEN_RE.search("\n".join(head.splitlines()[:5])))
    return _gen_cache[k]


def blame(repo, rev, path, extra=()):
    """Return {final_line_no: origin_sha} using --first-parent so origins are landed changes."""
    out = git(repo, "blame", "-w", "--first-parent", *extra, "--porcelain", rev, "--", path, check=False)
    res = {}
    for line in out.splitlines():
        m = re.match(r"^([0-9a-f]{40}) (\d+) (\d+)", line)
        if m:
            res[int(m.group(3))] = m.group(1)
    return res


def parse_diff(text):
    """Yield per-file dict: old, new, del_lines (old line numbers), add_lines (new line numbers), binary."""
    files, cur = [], None
    for line in text.splitlines():
        if line.startswith("diff --git "):
            cur = {"old": None, "new": None, "del": [], "add": [], "binary": False, "gitlink": False}
            files.append(cur)
            m = re.match(r'^diff --git "?a/(.*?)"? "?b/(.*?)"?$', line)
            if m:
                cur["old"], cur["new"] = m.group(1), m.group(2)
        elif cur is None:
            continue
        elif line.startswith("--- "):
            cur["old"] = None if line == "--- /dev/null" else line[6:] if line.startswith("--- a/") else cur["old"]
        elif line.startswith("+++ "):
            cur["new"] = None if line == "+++ /dev/null" else line[6:] if line.startswith("+++ b/") else cur["new"]
        elif line.startswith("Binary files"):
            cur["binary"] = True
        elif line.startswith("new file mode 160000") or line.startswith("index ") and line.endswith(" 160000"):
            cur["gitlink"] = True
        elif line.startswith("@@"):
            m = re.match(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@", line)
            os_, oc, ns, nc = int(m.group(1)), int(m.group(2) or 1), int(m.group(3)), int(m.group(4) or 1)
            cur["del"].extend(range(os_, os_ + oc))
            cur["add"].extend(range(ns, ns + nc))
        elif line.startswith("rename from "):
            cur["old"] = line[len("rename from "):]
        elif line.startswith("rename to "):
            cur["new"] = line[len("rename to "):]
        elif line.startswith("deleted file mode"):
            pass
    return files


def collect(repo, since, until, zone, merge_ids=None, extra_dirs=()):
    """Factory: every first-parent default-branch commit. Product: supplied PR merge OIDs.

    churn21/7 count deleted lines originated <=21/7 days earlier by first-parent
    blame; moved counts added lines attributed elsewhere by -M -C blame. Revisit
    counts changes touching a file touched by a counted change in the prior 7d.
    Exclude lock/generated names, generated headers, vendored/fixture directories,
    binaries and submodules. Diffs use rename detection and zero context.
    """
    remote = git(repo, 'symbolic-ref', '--quiet', 'refs/remotes/origin/HEAD', check=False).strip()
    local = remote.replace('refs/remotes/origin/', 'refs/heads/', 1) if remote else ''
    candidates = [local, 'refs/heads/main', 'refs/heads/master', remote, 'HEAD']
    ref = next((r for r in candidates if r and git(repo, 'rev-parse', '--verify', r, check=False).strip()), 'HEAD')
    log = git(repo, "log", "--first-parent", "--format=%H|%P|%ct", ref)
    commits = []
    for line in log.splitlines():
        sha, parents, ts = line.split("|")
        commits.append((sha, parents.split()[0] if parents else EMPTY, int(ts)))
    times = {sha: ts for sha, _, ts in commits}
    counted = {sha for sha, _, ts in commits if merge_ids is None or sha in merge_ids}
    rows, excluded = [], {}
    for sha, parent, ts in reversed(commits):
        if sha not in counted or not since.timestamp() - 7 * DAY <= ts < until.timestamp():
            continue
        row = dict(date=datetime.fromtimestamp(ts, zone).date().isoformat(), t=ts,
                   added=0, deleted=0, churn21=0, churn7=0, moved=0, revisit_changes=0, changes=1)
        touched = set()
        for f in parse_diff(git(repo, "diff", "-M", "-U0", "--no-color", "--no-ext-diff", parent, sha)):
            path = f["new"] or f["old"]
            reason = ("binary" if f["binary"] else "submodule" if f["gitlink"] else
                      excluded_path(repo, path, list(extra_dirs)))
            rev, fp = (sha, f["new"]) if f["new"] else (parent, f["old"])
            if not reason and generated_header(repo, rev, fp):
                reason = "generated header"
            if reason:
                excluded[path] = reason
                continue
            touched.update(p for p in (f["old"], f["new"]) if p)
            row["added"] += len(f["add"])
            row["deleted"] += len(f["del"])
            if f["del"] and f["old"] and parent != EMPTY:
                origins = blame(repo, parent, f["old"])
                for ln in f["del"]:
                    age = ts - times.get(origins.get(ln), -10**15)
                    row["churn21"] += 0 <= age <= 21 * DAY
                    row["churn7"] += 0 <= age <= 7 * DAY
            if f["add"] and f["new"] and parent != EMPTY:
                origins = blame(repo, sha, f["new"], ("-M", "-C"))
                row["moved"] += sum(bool(origins.get(ln)) and origins[ln] != sha for ln in f["add"])
        row["revisit_changes"] = int(any(touched & oldfiles for oldts, oldfiles, _ in rows
                                        if ts - 7 * DAY <= oldts < ts))
        rows.append((ts, touched, row))
    daily = [r for ts, _, r in rows if ts >= since.timestamp()]
    totals = {k: sum(r[k] for r in daily) for k in
              ("added", "deleted", "churn21", "churn7", "moved", "revisit_changes", "changes")}
    for key, numerator, denominator in (("churn21_ratio", "churn21", "added"),
                                        ("churn7_ratio", "churn7", "added"),
                                        ("moved_ratio", "moved", "added"),
                                        ("revisit_share", "revisit_changes", "changes")):
        totals[key] = totals[numerator] / totals[denominator] if totals[denominator] else None
    return {"daily": daily, "totals": totals, "excluded": excluded}
